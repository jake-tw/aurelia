-- ============================================================================
-- MySQL：建立 MCP 專用唯讀帳號
-- 注意事項：執行前請務必將下方範例中的「密碼」與「資料庫名稱」替換為實際設定
-- ============================================================================

-- 1. 建立使用者帳號
-- 'mcp_user'：自訂的帳號名稱
-- '%'：允許該帳號從任何外部 IP 位址連線（若 MCP 服務與資料庫在同一台主機，建議改為 'localhost' 以提高安全性）
-- IDENTIFIED BY '...'：設定該帳號的登入密碼（請替換為高強度密碼）
CREATE USER 'mcp_user'@'%' IDENTIFIED BY 'example';

-- 2. 授予唯讀權限（落實最小權限原則）
-- SELECT：允許讀取（查詢）資料表中的資料
-- SHOW VIEW：允許檢視檢視表（View）的結構與定義（部分 MCP 工具在讀取資料庫 Schema 時會需要此權限）
-- ON company.*：指定權限範圍為 'company' 資料庫底下的所有資料表（請將 company 替換為您的目標資料庫名稱）
GRANT SELECT, SHOW VIEW ON company.* TO 'mcp_user'@'%';

-- 3. 重新載入權限設定
-- 讓剛才新增的使用者與權限設定立即在資料庫中生效，無需重啟 MySQL 服務
FLUSH PRIVILEGES;
